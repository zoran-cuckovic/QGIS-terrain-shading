class ColourMix(QgsProcessingAlgorithm):
    """
    This algorithm simulates ambient lighting over a raster DEM (in input). 
    """
    # Constants used to refer to parameters and outputs. They will be
    # used when calling the algorithm from another algorithm, or when
    # calling from the QGIS console.
    HUE = 'INPUT'
    SHADE = 'SHADE'
    COLOUR_STRENGTH= 'COLOUR_STRENGTH'
    

    #RANGE = 'RANGE'
    OUTPUT = 'OUTPUT'
    ANALYSIS_TYPES = ['Sky-view','Openness']
    DENOISE_TYPES= ['None', 'Mean', 'Median', 'Mean and median']
    output_model = None #for post-processing
    def initAlgorithm(self, config):
        """
        Here we define the inputs and output of the algorithm, along
        with some other properties.
        """
        self.addParameter(
            QgsProcessingParameterRasterLayer(
                self.HUE,
                self.tr('Hue')
            ) )
        self.addParameter(
            QgsProcessingParameterRasterLayer(
                self.SHADE,
                self.tr('Shade')
            ) )
        self.addParameter(
            QgsProcessingParameterRasterLayer(
                self.COLOUR_STRENGTH,
                self.tr('Colour saturation')
            ) )

        self.addParameter(
            QgsProcessingParameterRasterDestination(
                self.OUTPUT,
            self.tr("RGB composite")))
        
    def processAlgorithm(self, parameters, context, feedback):
        """
        Here is where the processing itself takes place.
        """
        hue = self.parameterAsRasterLayer(parameters,self.HUE, context)
        level= self.parameterAsRasterLayer(parameters,self.SHADE, context)
        saturation= self.parameterAsRasterLayer(parameters,self.COLOUR_STRENGTH, context)
        
        self.output_model = self.parameterAsOutputLayer(parameters,self.OUTPUT,context)
        h = rs.Raster(hue)
        l = rs.Raster(level)
        s = rs.Raster(saturation)
        

        h.set_output(self.output_model, bands = 3)
    
       # normalised 
        mx_h = h.read_entire() / h.max
        mx_l =  l.read_entire() / l.max  
        mx_s = s.read_entire() /s.max
        
        r, g, b = hsv_to_rgb(mx_h, mx_s, mx_l )
        h.add_to_buffer(r, band = 1)
        h.add_to_buffer(g, band = 2) 
        h.add_to_buffer(b, band = 3)
            
        return {self.OUTPUT: self.output_model}


    def name(self):
        """
        Returns the algorithm name, used for identifying the algorithm. This
        string should be fixed for the algorithm, and must not be localised.
        The name should be unique within each provider. Names should contain
        lowercase alphanumeric characters only and no spaces or other
        formatting characters.
        """
        return 'colour_mix '

    def displayName(self):
        """
        Returns the translated algorithm name, which should be used for any
        user-visible display of the algorithm name.
        """
        return "Colour mixing"

